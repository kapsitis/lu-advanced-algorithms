    typedef const uint8_t (&table_t)[256];

    template<table_t lut0, table_t lut1, table_t lut2, table_t lut3>
    std::vector<std::pair<uint32_t, uint32_t>> run_impl(std::vector<std::pair<uint32_t, uint64_t>> data,
                                                        int collision_number_to_use,
                                                        int top_count_to_return) {
        struct key_solutions_t {
            uint8_t a = 0, b = 0, c = 0, d = 0;
        };

        std::vector<key_solutions_t> key_solutions(255 * 128 * 256);
        for (int x = 0, xy = 0; x < 256; x++)
            for (int y = 0; y < x; y++, xy++)
                for (int k = 0; k < 256; k++) {
                    int v = lut3[x ^ k] ^ lut3[y ^ k];
                    auto& solutions = key_solutions[(xy << 8) | v];
                    if (solutions.b == 0) {
                        solutions.a = k;
                        solutions.b = k ^ x ^ y;
                    }
                    else if (solutions.b != k) {
                        solutions.c = k;
                        solutions.d = k ^ x ^ y;
                    }
                }

        struct data_t {
            uint8_t input[4];
            uint64_t value;

            data_t(uint32_t input_mask, uint64_t value) : value(value) {
                for (int i = 0; i < 4; i++) {
                    input[i] = (input_mask >> (8 * i)) & 0xFF;
                }
            }

            bool operator < (const data_t& rhs) const {
                return value < rhs.value;
            }
        };

        std::vector<data_t> traces;
        for (auto& p : data) {
            traces.emplace_back(p.first, p.second);
        }

        std::sort(traces.begin(), traces.end());

        {
            size_t n = 0;
            for (size_t i = 0; i < traces.size(); i++) {
                if ((n != 0 && traces[i].value == traces[n - 1].value) || (i + 1 < traces.size() && traces[i].value == traces[i + 1].value)) {
                    traces[n++] = traces[i];
                }
            }

            traces.erase(traces.begin() + n, traces.end());
        }

        const int N = traces.size();

        std::vector<std::tuple<int, int, int>> collisions;
        std::vector<std::pair<int, int>> zero_collisions;
        int collision_count = 0;
        for (int i = 0; i < N; i++)
            for (int j = i + 1; j < N && traces[i].value == traces[j].value && collision_count < collision_number_to_use; j++) {
                int x = traces[i].input[3];
                int y = traces[j].input[3];
                if (x == y) {
                    zero_collisions.emplace_back(i, j);
                }
                else {
                    if (x < y) std::swap(x, y);
                    collisions.emplace_back(i, j, (x * (x - 1) / 2 + y) << 8);
                }

                collision_count++;
            }

        std::fprintf(stderr, "Using %d collisions (limit = %d).\n", collision_count, collision_number_to_use);

        int min_votes;
        {
            std::vector<long double> log_factorial(collision_count + 1, 0);
            for (int i = 2; i <= collision_count; i++) {
                log_factorial[i] = log_factorial[i - 1] + std::log2(i);
            }

            long double log_255 = std::log2(255);

            int64_t target_count = top_count_to_return * 2 + 10;
            min_votes = collision_count + 1;
            while (target_count > 0) {
                min_votes--;

                long double log_here = log_factorial[collision_count] - log_factorial[min_votes] -
                                       log_factorial[collision_count - min_votes] +
                                       log_255 * (collision_count - min_votes) -
                                       8 * collision_count + 32;

                target_count -= std::exp2(log_here);
            }
        }

        std::vector<std::pair<uint32_t, uint32_t>> result;
        std::vector<unsigned char> values(N);

        for (uint32_t k_mask = 0; k_mask < (1 << 24); k_mask++) {
            uint32_t k0 = k_mask & 0xFF;
            uint32_t k1 = (k_mask >> 8) & 0xFF;
            uint32_t k2 = (k_mask >> 16) & 0xFF;

            for (int i = 0; i < N; i++) {
                values[i] = lut0[traces[i].input[0] ^ k0] ^
                            lut1[traces[i].input[1] ^ k1] ^
                            lut2[traces[i].input[2] ^ k2];
            }

            static int votes[256];

            int all_key_votes = 0;
            for (auto& p : zero_collisions) {
                int i = p.first, j = p.second;
                int v = values[i] ^ values[j];
                if (v == 0) all_key_votes++;
            }

            const int THRESHOLD = 80;

            if (collisions.size() > THRESHOLD || all_key_votes >= min_votes) {
                for (auto& p : collisions) {
                    int i, j, xy;
                    std::tie(i, j, xy) = p;
                    int v = values[i] ^ values[j];

                    auto& solutions = key_solutions[xy | v];

                    if (solutions.b != 0) {
                        votes[solutions.a]++;
                        votes[solutions.b]++;
                    }

                    if (solutions.c != 0) {
                        votes[solutions.c]++;
                        votes[solutions.d]++;
                    }
                }

                for (uint32_t k = 0; k < 256; k++) {
                    if (all_key_votes + votes[k] >= min_votes) {
                        result.emplace_back(all_key_votes + votes[k], k_mask + (k << 24));
                    }
                }

                std::memset(votes, 0, sizeof votes);
            }
            else {
                static uint8_t ks[THRESHOLD * 4];
                int kcnt = 0;

                for (auto& p : collisions) {
                    int i, j, xy;
                    std::tie(i, j, xy) = p;
                    int v = values[i] ^ values[j];

                    auto& solutions = key_solutions[xy | v];

#define vote(k)\
                        votes[k]++;\
                        ks[kcnt++] = k;

                    if (solutions.b != 0) {
                        vote(solutions.a);
                        vote(solutions.b);
                    }

                    if (solutions.c != 0) {
                        vote(solutions.c);
                        vote(solutions.d);
                    }
#undef vote
                }

                for (int i = 0; i < kcnt; i++) {
                    int k = ks[i];
                    if (votes[k] != 0) {
                        if (all_key_votes + votes[k] >= min_votes) {
                            result.emplace_back(all_key_votes + votes[k], k_mask + (k << 24));
                        }

                        votes[k] = 0;
                    }
                }
            }
        }

        std::sort(result.begin(), result.end(), std::greater<std::pair<uint32_t, uint32_t>>{});

        std::fprintf(stderr, "Found %zu solutions (target = %d, min votes = %d):\n", result.size(), top_count_to_return, min_votes);

        std::map<int, int> keys_with_votes;
        for (auto& p : result) {
            keys_with_votes[p.first]++;
        }

        for (auto& p : keys_with_votes) {
            printf("%9d keys with %4d votes\n", p.second, p.first);
        }

//        if (result.size() > top_count_to_return) result.resize(top_count_to_return);

        return result;
    }

    std::vector<std::pair<uint32_t, uint32_t>> run(
            const std::vector<std::pair<uint32_t, uint64_t>>& data,
            int collision_number_to_use,
            int top_count_to_return,
            bool from_output) {
        auto impl = from_output ? run_impl<SinvE, SinvB, SinvD, Sinv9> :
                                  run_impl<Sbox2, Sbox3, Sbox1, Sbox1>;
        return impl(data, collision_number_to_use, top_count_to_return);
    }
